// Helper functions
export function getPlacesByUser(userId) {
  return dummyPlaces.filter(p => p.userId === userId)
}

export function getPlacesByCategory(category) {
  if (!category) return dummyPlaces
  return dummyPlaces.filter(p => p.category === category)
}

export function getPlacesByLokasi(lokasi) {
  if (!lokasi) return dummyPlaces
  return dummyPlaces.filter(p => p.lokasi === lokasi)
}

export function getPlaceById(id) {
  return dummyPlaces.find(p => p.id === id)
}

export function searchPlaces(query) {
  const q = query.toLowerCase()
  return dummyPlaces.filter(
    p =>
      p.name.toLowerCase().includes(q) ||
      p.bio?.toLowerCase().includes(q) ||
      p.tags?.some(t => t.toLowerCase().includes(q)) ||
      p.lokasi.toLowerCase().includes(q)
  )
}
